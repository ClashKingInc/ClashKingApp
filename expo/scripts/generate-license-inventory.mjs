import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const lock = JSON.parse(fs.readFileSync(path.join(root, 'package-lock.json'), 'utf8'));
const output = path.join(root, 'src/features/settings/presentation/generated-license-inventory.ts');

const packageRecords = Object.entries(lock.packages)
  .filter(([packagePath, metadata]) => packagePath.startsWith('node_modules/') && !metadata.dev)
  .map(([packagePath, metadata]) => {
    const directory = path.join(root, packagePath);
    const manifestPath = path.join(directory, 'package.json');
    const manifest = fs.existsSync(manifestPath)
      ? JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
      : {};
    const declaredLicense =
      metadata.license ??
      manifest.license ??
      manifest.licenses
        ?.map(({ type }) => type)
        .filter(Boolean)
        .join(' OR ');
    const licenseFile = fs.existsSync(directory)
      ? fs
          .readdirSync(directory)
          .find(
            (name) =>
              /^(licen[cs]e|copying|notice)([.\-_]|$)/i.test(name) &&
              fs.statSync(path.join(directory, name)).isFile(),
          )
      : undefined;
    return {
      name: manifest.name ?? packagePath.slice('node_modules/'.length),
      version: metadata.version ?? manifest.version ?? '',
      license: declaredLicense ?? '',
      text: licenseFile
        ? fs.readFileSync(path.join(directory, licenseFile), 'utf8').trim()
        : undefined,
    };
  })
  .filter(({ name }) => name !== '@clashking/native');

// npm packages frequently omit a duplicate LICENSE file from small subpackages.
// Reuse the verbatim text from another installed package declaring the same SPDX
// expression so every shipped third-party package remains represented.
const textByLicense = new Map();
for (const entry of packageRecords) {
  if (entry.license && entry.text && !textByLicense.has(entry.license)) {
    textByLicense.set(entry.license, entry.text);
  }
}
for (const entry of packageRecords) {
  entry.text ??= textByLicense.get(entry.license);
  if (!entry.text && entry.license) {
    const alternatives = entry.license.match(/[A-Za-z0-9.-]+/g) ?? [];
    const texts = alternatives
      .map((identifier) => textByLicense.get(identifier))
      .filter((text, index, values) => text && values.indexOf(text) === index);
    if (texts.length > 0) entry.text = texts.join('\n\n----- OR -----\n\n');
  }
}

const unresolved = packageRecords.filter(({ license, text }) => !license || !text);
if (unresolved.length > 0) {
  throw new Error(
    `Missing license metadata or text for: ${unresolved
      .map(({ name, version }) => `${name}@${version}`)
      .join(', ')}`,
  );
}

const groups = new Map();
for (const entry of packageRecords) {
  const key = `${entry.license}\0${entry.text}`;
  const group = groups.get(key) ?? { packages: [], license: entry.license, text: entry.text };
  group.packages.push(`${entry.name}@${entry.version}`);
  groups.set(key, group);
}
const inventory = [...groups.values()]
  .map((entry) => ({ ...entry, packages: [...new Set(entry.packages)].sort() }))
  .sort((left, right) => left.packages[0].localeCompare(right.packages[0]));

const source = `// Generated by scripts/generate-license-inventory.mjs. Do not edit.\n\nexport interface GeneratedLicenseEntry {\n  readonly packages: readonly string[];\n  readonly license: string;\n  readonly text: string;\n}\n\nexport const GENERATED_LICENSE_INVENTORY: readonly GeneratedLicenseEntry[] = ${JSON.stringify(
  inventory,
  null,
  2,
)};\n`;
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output, 'utf8') !== source) {
    throw new Error('Generated license inventory is out of date. Run npm run licenses:generate.');
  }
} else {
  fs.writeFileSync(output, source);
}
console.log(
  `Generated ${inventory.length} license texts covering ${packageRecords.length} production packages.`,
);
