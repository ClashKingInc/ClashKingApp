import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

// The bot owns the composition. Check generated parity without contacting any service:
// node scripts/sync-legend-poster.mjs /path/to/clashking_bot --check
const root = fileURLToPath(new URL('../', import.meta.url));
const bot = process.argv[2];
if (!bot) throw new Error('Pass the clashking_bot checkout path.');
const check = process.argv.includes('--check');
const source = resolve(bot, 'worker/src/commands/legend-poster-layout.ts');
const destination = resolve(root, 'src/core/graphics/legend-poster-layout.ts');
const generated =
  '// Generated from clashking_bot; run scripts/sync-legend-poster.mjs to update.\n' +
  (await readFile(source, 'utf8'));
if (check) {
  if ((await readFile(destination, 'utf8')) !== generated)
    throw new Error('Poster layout is out of sync.');
} else {
  await mkdir(resolve(root, 'src/core/graphics'), { recursive: true });
  await writeFile(destination, generated);
}
const names = [
  'sword',
  'shield',
  'trophy',
  'legend',
  'star',
  'clashking',
  'league-prince',
  'heart',
  ...Array.from({ length: 18 }, (_, index) => `th${index + 1}`),
];
for (const filename of [...names.map((name) => name + '.png'), 'blogger.ttf', 'clash.ttf']) {
  const from = resolve(bot, 'worker/src/assets/legend-poster', filename);
  const to = resolve(root, 'assets/clashking/legend-poster', filename);
  if (check) {
    if (!(await readFile(from)).equals(await readFile(to)))
      throw new Error(`Poster asset differs: ${filename}`);
  } else {
    await mkdir(resolve(root, 'assets/clashking/legend-poster'), { recursive: true });
    await copyFile(from, to);
  }
}
const assetSource =
  '// Generated by scripts/sync-legend-poster.mjs.\n' +
  'export const legendPosterAssets = {\n' +
  names
    .map(
      (name) =>
        `  '${name}': require('../../../assets/clashking/legend-poster/${name}.png') as number,\n`,
    )
    .join('') +
  '};\n';
const assetDestination = resolve(root, 'src/core/graphics/legend-poster-assets.ts');
if (check) {
  if ((await readFile(assetDestination, 'utf8')) !== assetSource)
    throw new Error('Poster asset map differs.');
} else await writeFile(assetDestination, assetSource);
console.log(
  check ? 'Bot/app poster layout and assets match.' : 'Synced bot poster layout and assets.',
);
