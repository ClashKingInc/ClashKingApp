import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
// Generate the landing's tiny modules from the native app's authoritative
// parser. No React, Expo, API client or account state enters the public site.
export async function prepareAppLanding() {
  const directory = join(root, 'public', 'landing');
  await mkdir(directory, { recursive: true });
  // Build and local Metro use the same optional, validated store destinations.
  // Missing URLs leave visible Coming soon cards, never fabricated listings.
  const stores = {};
  for (const [label, value, host] of [
    ['App Store', process.env.CK_IOS_STORE_URL, 'apps.apple.com'],
    ['Google Play', process.env.CK_ANDROID_STORE_URL, 'play.google.com'],
  ]) {
    if (!value) continue;
    const url = new URL(value);
    if (url.protocol !== 'https:' || url.hostname !== host || url.username || url.password)
      throw new Error('Invalid ' + label + ' URL');
    stores[label] = url.href;
  }
  await writeFile(
    join(directory, 'store-links.js'),
    '/* Generated by prepare-app-landing.mjs. */\nexport const storeLinks = ' +
      JSON.stringify(stores).replaceAll('<', '\\u003c') +
      ';\n',
  );
  for (const [source, target] of [
    ['src/navigation/route-manifest.ts', 'route-manifest.js'],
    ['src/core/deep-links/app-link.ts', 'app-link.js'],
  ]) {
    const input = await readFile(join(root, source), 'utf8');
    const output = ts.transpileModule(input, {
      compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 },
    }).outputText;
    await writeFile(
      join(directory, target),
      '// Generated from ' +
        source +
        '. Do not edit.\n' +
        output.replace("'../../navigation/route-manifest'", "'./route-manifest.js'"),
    );
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url))
  await prepareAppLanding();
