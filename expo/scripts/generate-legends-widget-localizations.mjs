import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const expoRoot = resolve(scriptDirectory, '..');
const arbRoot = resolve(expoRoot, 'src/i18n/arb');
const androidRoot = resolve(expoRoot, 'native/android/app/src/main/res');
const iosCatalogPath = resolve(
  expoRoot,
  'native/ios/WarWidget/LegendsWidget.xcstrings',
);

const resources = {
  legends_widget_label: 'legendsTitle',
  legends_widget_description: 'legendsTitle',
  legends_widget_player_label: 'exportLabelPlayer',
  legends_widget_town_hall_description: 'filtersTownHall',
  legends_widget_clan_badge_description: 'clanTitle',
  legends_widget_day: 'statsDayIndex',
  legends_widget_attacks: 'rankedLeagueAttacks',
  legends_widget_defenses: 'rankedLeagueDefenses',
  legends_widget_global_rank: 'legendsGlobalRankTitle',
  legends_widget_rank: 'cwlRankTitle',
  legends_widget_recent: 'searchRecent',
  legends_widget_stale: 'widgetDataStale',
  legends_widget_updated: 'upgradeTrackerHeaderUpdated',
  legends_widget_no_data: 'generalNoDataAvailable',
  legends_widget_configure_eyebrow: 'legendsTitle',
  legends_widget_configure_title: 'upgradeTrackerChooseAccount',
  legends_widget_configure_description: 'upgradeTrackerChooseAccount',
  legends_widget_configure_empty: 'playersNoBookmarkedTitle',
  legends_widget_configure_automatic: 'playersBookmarked',
  legends_widget_configure_add: 'accountsAdd',
  legends_widget_player_picker_description: 'upgradeTrackerChooseAccount',
};

const catalogs = readdirSync(arbRoot)
  .filter((file) => /^app_[A-Za-z_]+\.arb$/.test(file))
  .sort((left, right) => left.localeCompare(right))
  .map((file) => ({
    locale: file.slice('app_'.length, -'.arb'.length),
    messages: readArb(file),
  }));

if (catalogs.length !== 33) {
  throw new Error(`Expected 33 ARB catalogs, found ${catalogs.length}`);
}

for (const { locale, messages } of catalogs) {
  for (const sourceKey of new Set(Object.values(resources))) {
    if (typeof messages[sourceKey] !== 'string') {
      throw new Error(`Missing source message ${locale}.${sourceKey}`);
    }
  }
}

const english = catalogs.find(({ locale }) => locale === 'en')?.messages;
if (!english) throw new Error('Missing source catalog app_en.arb');
for (const { locale, messages } of catalogs) {
  if (locale === 'en' || locale.startsWith('en_')) continue;
  const copiedEnglish = [...new Set(Object.values(resources))]
    .every((sourceKey) => messages[sourceKey] === english[sourceKey]);
  if (copiedEnglish) {
    throw new Error(`${locale} native widget messages unexpectedly match English`);
  }
}

const expected = new Map();
for (const catalog of catalogs) {
  const directory = androidValuesDirectory(catalog.locale);
  expected.set(
    resolve(androidRoot, directory, 'legends_widget_strings.xml'),
    androidDocument(catalog),
  );
}
expected.set(iosCatalogPath, iosDocument(catalogs));

if (process.argv.includes('--check')) {
  for (const [path, contents] of expected) {
    let actual;
    try {
      actual = readFileSync(path, 'utf8');
    } catch {
      throw new Error(`Generated localization is missing: ${path}`);
    }
    if (actual !== contents) throw new Error(`Generated localization is stale: ${path}`);
  }
} else {
  for (const [path, contents] of expected) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, contents);
  }
}

function readArb(file) {
  return JSON.parse(readFileSync(resolve(arbRoot, file), 'utf8'));
}

function androidValuesDirectory(locale) {
  if (locale === 'en') return 'values';
  const [language, region] = locale.split('_');
  const androidLanguage = language === 'he' ? 'iw' : language;
  return region
    ? `values-${androidLanguage}-r${region.toUpperCase()}`
    : `values-${androidLanguage}`;
}

function androidDocument({ messages }) {
  const strings = Object.entries(resources)
    .map(([resourceKey, sourceKey]) => {
      const value = androidValue(messages[sourceKey], sourceKey);
      return `    <string name="${resourceKey}">${value}</string>`;
    })
    .join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by scripts/generate-legends-widget-localizations.mjs. -->\n<resources>\n${strings}\n</resources>\n`;
}

function androidValue(message, sourceKey) {
  const formatted = sourceKey === 'statsDayIndex'
    ? message.replace('{index}', '%1$d')
    : message;
  return formatted
    .replaceAll('\\', '\\\\')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll("'", "\\'")
    .replaceAll('\n', '\\n');
}

function iosDocument(allCatalogs) {
  const strings = Object.fromEntries(
    Object.entries(resources).map(([resourceKey, sourceKey]) => [
      resourceKey,
      {
        comment: `Generated from ARB key ${sourceKey}.`,
        extractionState: 'manual',
        localizations: Object.fromEntries(
          allCatalogs.map(({ locale, messages }) => [
            locale.replace('_', '-'),
            {
              stringUnit: {
                state: 'translated',
                value: messages[sourceKey],
              },
            },
          ]),
        ),
      },
    ]),
  );
  return `${JSON.stringify({ sourceLanguage: 'en', strings, version: '1.0' }, null, 2)}\n`;
}
