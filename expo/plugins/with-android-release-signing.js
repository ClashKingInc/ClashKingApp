'use strict';

const { withAppBuildGradle } = require('expo/config-plugins');

const SIGNING_MARKER = '// ClashKing release signing (generated by Expo config plugin).';

function configureAndroidReleaseSigning(contents) {
  if (contents.includes(SIGNING_MARKER)) return contents;

  const signingSection = /(\n    signingConfigs \{\n)([\s\S]*?)(\n    \}\n    buildTypes \{)/;
  const match = signingSection.exec(contents);
  if (!match) throw new Error('Generated Android build.gradle has no signingConfigs block.');

  const releaseConfig = `
        ${SIGNING_MARKER}
        release {
            def keyStore = findProperty('CK_UPLOAD_STORE_FILE')
            if (keyStore) {
                storeFile file(keyStore)
                storePassword findProperty('CK_UPLOAD_STORE_PASSWORD')
                keyAlias findProperty('CK_UPLOAD_KEY_ALIAS')
                keyPassword findProperty('CK_UPLOAD_KEY_PASSWORD')
            }
        }`;
  let configured = contents.replace(
    signingSection,
    `${match[1]}${match[2]}${releaseConfig}${match[3]}`,
  );

  const buildTypesStart = configured.indexOf('\n    buildTypes {');
  const packagingStart = configured.indexOf('\n    packagingOptions', buildTypesStart);
  if (buildTypesStart < 0 || packagingStart < 0) {
    throw new Error('Generated Android build.gradle has no buildTypes section.');
  }
  const beforeBuildTypes = configured.slice(0, buildTypesStart);
  const buildTypes = configured.slice(buildTypesStart, packagingStart);
  const afterBuildTypes = configured.slice(packagingStart);
  const releaseBuildType = /(\n        release \{\n)([\s\S]*?)(\n        \})/;
  const releaseMatch = releaseBuildType.exec(buildTypes);
  if (!releaseMatch) throw new Error('Generated Android build.gradle has no release build type.');
  const releaseBody = releaseMatch[2].replace(
    /signingConfig signingConfigs\.debug/,
    'signingConfig signingConfigs.release',
  );
  if (!releaseBody.includes('signingConfig signingConfigs.release')) {
    throw new Error('Unable to configure the Android release signing config.');
  }
  const configuredBuildTypes = buildTypes.replace(
    releaseBuildType,
    `${releaseMatch[1]}${releaseBody}${releaseMatch[3]}`,
  );
  return `${beforeBuildTypes}${configuredBuildTypes}${afterBuildTypes}`;
}

function withAndroidReleaseSigning(config) {
  return withAppBuildGradle(config, (mod) => {
    if (mod.modResults.language !== 'groovy') {
      throw new Error('ClashKing Android release signing requires a Groovy app build.gradle.');
    }
    mod.modResults.contents = configureAndroidReleaseSigning(mod.modResults.contents);
    return mod;
  });
}

module.exports = withAndroidReleaseSigning;
module.exports.configureAndroidReleaseSigning = configureAndroidReleaseSigning;
